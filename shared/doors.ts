/** حدود النقاط للمستويات: المستوى 1 من 0-49، المستوى 2 من 50-149، المستوى 3 من 150-299، المستوى 4 من 300+ */
export const LEVEL_THRESHOLDS = [0, 50, 150, 300] as const;

export function computeLevel(points: number): number {
  if (points < 50) return 1;
  if (points < 150) return 2;
  if (points < 300) return 3;
  return 4;
}

export function levelProgress(points: number): { percent: number; toNext: number } {
  const level = computeLevel(points);
  if (level === 4) return { percent: 100, toNext: 0 };
  const currentNeed = LEVEL_THRESHOLDS[level - 1];
  const nextNeed = LEVEL_THRESHOLDS[level];
  const percent = Math.round(((points - currentNeed) / (nextNeed - currentNeed)) * 100);
  return { percent, toNext: nextNeed - points };
}

